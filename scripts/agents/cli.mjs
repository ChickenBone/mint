#!/usr/bin/env node
// Agent domain tooling. Usage: npm run agents -- <command>  (see `help`).
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  GEN_END,
  GEN_START,
  SOURCE_EXT,
  TEST_FILE,
  applyToSafe,
  compileManifest,
  exportedNames,
  importSpecifiers,
  loadWorkspaces,
  replaceBlock,
  resolveImport,
  resolveOwnership,
  routeQuery,
  splitCard,
  workspaceFor,
} from "./lib.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const MANIFEST = "agents/domains.json";
const CARDS_DIR = "agents/domains";
const INSTRUCTIONS_DIR = ".github/instructions";
const INSTRUCTIONS_MARK = "<!-- generated by `npm run agents:sync` from agents/domains.json -->";
const TEXT_EXT = /\.(?:[cm]?[jt]sx?|json|md|ya?ml|css|sql|sh|txt|html|svg)$|(?:^|\/)(?:Dockerfile|\.[\w.-]+)$/;

const abs = (p) => path.join(ROOT, p);
const read = (p) => readFileSync(abs(p), "utf8");
const git = (...args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const gitLines = (...args) => git(...args).split("\n").filter(Boolean);

// ---------- context ----------

function loadContext() {
  const manifest = JSON.parse(read(MANIFEST));
  const compiled = compileManifest(manifest);
  const files = [...new Set(gitLines("ls-files", "-co", "--exclude-standard"))].filter((f) => existsSync(abs(f))).sort();
  const ownership = resolveOwnership(compiled, files);
  const workspaces = loadWorkspaces(ROOT);
  return { manifest, compiled, files, fileSet: new Set(files), ...ownership, workspaces, cache: new Map() };
}

function source(ctx, file) {
  if (!ctx.cache.has(file)) ctx.cache.set(file, TEXT_EXT.test(file) ? read(file) : null);
  return ctx.cache.get(file);
}

const filesOf = (ctx, id) => [...ctx.owners].filter(([, d]) => d === id).map(([f]) => f);

/** Cross-domain import edges: Map<from, Map<to, [[fromFile, toFile]]>> */
function importGraph(ctx) {
  if (ctx.graph) return ctx.graph;
  const graph = new Map();
  for (const [file, from] of ctx.owners) {
    if (!SOURCE_EXT.test(file)) continue;
    const src = source(ctx, file);
    if (!src) continue;
    for (const spec of importSpecifiers(src)) {
      const target = resolveImport(spec, file, ctx.fileSet, ctx.workspaces);
      const to = target && ctx.owners.get(target);
      if (!to || to === from) continue;
      if (!graph.has(from)) graph.set(from, new Map());
      const m = graph.get(from);
      if (!m.has(to)) m.set(to, []);
      m.get(to).push([file, target]);
    }
  }
  ctx.graph = graph;
  return graph;
}

function dependencies(ctx, id) {
  const g = importGraph(ctx);
  const out = [...(g.get(id)?.keys() ?? [])].sort();
  const inn = [...g].filter(([, m]) => m.has(id)).map(([d]) => d).sort();
  return { out, inn };
}

/** Session-relevant size: binary assets (screenshots, icons) are not read by agents, so they are excluded. */
function domainSize(ctx, id) {
  let lines = 0;
  let files = 0;
  for (const f of filesOf(ctx, id)) {
    const s = source(ctx, f);
    if (s === null) continue;
    files++;
    lines += s.split("\n").length;
  }
  return { files, lines };
}

// ---------- validation commands ----------

function testRunner(ws) {
  const script = ws.scripts.test;
  if (!script) return "node --test";
  const tokens = script.split(/\s+/);
  const runner = [];
  for (const t of tokens) {
    if (/[*/]|\.test\./.test(t)) break;
    runner.push(t);
  }
  return runner.join(" ") || "node --test";
}

/**
 * Focused commands for `files`. `changed` (affected mode) holds the files actually modified: a shared-package
 * change escalates to a root typecheck, and schema notes appear only when schema files changed.
 */
function validationFor(ctx, files, extra = [], changed = null) {
  const cmds = [];
  const notes = new Set();
  const wsHit = new Map();
  const rootTests = [];
  const schemaFile = (f) => f.startsWith("packages/core/migrations/") || /^packages\/core\/src\/db\/[^/]+\.ts$/.test(f);
  for (const f of files) {
    const ws = workspaceFor(ctx.workspaces, f);
    if (ws) {
      if (!wsHit.has(ws.dir)) wsHit.set(ws.dir, { ws, tests: [] });
      if (TEST_FILE.test(f)) wsHit.get(ws.dir).tests.push(f.slice(ws.dir.length + 1));
    } else if (TEST_FILE.test(f)) rootTests.push(f);
    if (/\.integration\.test\./.test(f) || /-db\.test\./.test(f)) {
      notes.add("Integration/DB tests skip without PostgreSQL/Redis/audio env vars; see `.github/workflows/ci.yml`. A skip is not a pass.");
    }
  }
  const shared = (f) => ctx.workspaces.some((w) => w.dir.startsWith("packages/") && f.startsWith(`${w.dir}/`));
  const sharedChanged = changed ? changed.some(shared) : false;
  if (sharedChanged) cmds.push("npm run typecheck  # shared package changed: every consumer must typecheck");
  else if (!changed && files.some(shared)) notes.add("Changing owned `packages/*` files affects every consumer: run root `npm run typecheck` (`npm run agents -- affected` does this automatically).");
  if ((changed ?? files).some(schemaFile)) {
    notes.add(changed ? "Schema changed: add a new migration via `npm run db:generate`; never rewrite applied migrations." : "If you change the schema, add a new migration via `npm run db:generate`; never rewrite applied migrations.");
  }
  for (const { ws, tests } of [...wsHit.values()].sort((a, b) => a.ws.dir.localeCompare(b.ws.dir))) {
    if (!sharedChanged && ws.scripts.typecheck) cmds.push(`npm run typecheck -w ${ws.name}`);
    if (ws.scripts.lint) cmds.push(`npm run lint -w ${ws.name}`);
    if (tests.length) cmds.push(`npm exec -w ${ws.name} -- ${testRunner(ws)} ${tests.sort().join(" ")}`);
  }
  if (rootTests.length) cmds.push(`node --test ${rootTests.sort().join(" ")}`);
  for (const c of extra) if (!cmds.includes(c)) cmds.push(c);
  return { cmds, notes: [...notes] };
}

// ---------- rendering ----------

function groupFiles(files) {
  const groups = new Map();
  for (const f of files) {
    const parts = f.split("/");
    const dirParts = parts.slice(0, -1);
    const key = dirParts.slice(0, 5).join("/") || ".";
    const rest = parts.slice(Math.min(dirParts.length, 5)).join("/");
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(rest);
  }
  return [...groups].sort((a, b) => a[0].localeCompare(b[0]));
}

const link = (fromDir, target) => `[${target}](${path.posix.relative(fromDir, target)})`;

function renderCardBlock(ctx, d) {
  const files = filesOf(ctx, d.id);
  const tests = files.filter((f) => TEST_FILE.test(f));
  const { out, inn } = dependencies(ctx, d.id);
  const { cmds, notes } = validationFor(ctx, files, d.validate);
  const ids = (list) => (list.length ? list.map((x) => `[\`${x}\`](${x}.md)`).join(", ") : "none");
  const lines = [
    GEN_START,
    "",
    "## Generated map",
    "",
    `- **Scope:** ${d.summary}.`,
    `- **Read before editing:** ${d.guides.map((g) => link(CARDS_DIR, g)).join(", ") || "this card"}${d.ui ? " (UI: also check desktop/mobile per DESIGN.md)" : ""}.`,
    `- **Imports from:** ${ids(out)}`,
    `- **Imported by:** ${ids(inn)}`,
    `- **Live detail:** \`npm run agents -- map ${d.id}\` (exports, line counts, cross-domain import edges).`,
    "",
    `### Owned files (${files.length})`,
    "",
    ...groupFiles(files).map(([dir, items]) => `- \`${dir}/\` ${items.map((i) => `\`${i}\``).join(", ")}`),
    "",
    "### Validate",
    "",
    tests.length ? `Owned tests: ${tests.length}.` : "No owned automated tests; add focused tests with behavior changes.",
    "",
    "```bash",
    ...(cmds.length ? cmds : ["npm run agents:check"]),
    "```",
    ...(notes.length ? ["", ...notes.map((n) => `> ${n}`)] : []),
    "",
    GEN_END,
  ];
  return lines.join("\n");
}

function cardSkeleton(d) {
  return [
    `# ${d.title} (\`${d.id}\`)`,
    "",
    `> ${d.summary}.`,
    "",
    "## Boundaries",
    "",
    "- TODO: what this domain owns and must never do.",
    "",
    "## Invariants",
    "",
    "- TODO: behavior that must be preserved.",
    "",
    "## Entry points and gotchas",
    "",
    "- TODO: where to start reading.",
    "",
  ].join("\n");
}

function renderIndex(ctx) {
  const rows = ctx.compiled.domains.map((d) => {
    const { out } = dependencies(ctx, d.id);
    return `| [\`${d.id}\`](${d.id}.md) | ${d.summary} | ${filesOf(ctx, d.id).length} | ${out.map((x) => `\`${x}\``).join(" ") || "—"} |`;
  });
  return [
    "# Domain index",
    "",
    "<!-- Generated by `npm run agents:sync` from agents/domains.json. Do not edit. -->",
    "",
    "Each domain is a bounded context an agent session can hold at once. Cards list owned files, invariants, dependencies and focused validation. See [working at scale](../working-at-scale.md) for the protocol and maintenance rules.",
    "",
    "| Domain | Scope | Files | Imports from |",
    "| --- | --- | ---: | --- |",
    ...rows,
    "",
  ].join("\n");
}

function renderRoutingBlock(ctx) {
  return [
    GEN_START,
    "",
    "| Domain | Covers |",
    "| --- | --- |",
    ...ctx.compiled.domains.map((d) => `| [\`${d.id}\`](${CARDS_DIR}/${d.id}.md) | ${d.summary} |`),
    "",
    GEN_END,
  ].join("\n");
}

/** Directories whose every (non-ignored) file is owned by `id`, so `dir/**` is exact today and covers future files. */
function fullyOwnedDirs(ctx, id) {
  const status = new Map(); // dir -> true when all files beneath are owned by id
  for (const f of ctx.files) {
    if (ctx.compiled.ignoreRes.some((re) => re.test(f))) continue;
    const mine = ctx.owners.get(f) === id;
    const parts = f.split("/");
    for (let i = 1; i < parts.length; i++) {
      const dir = parts.slice(0, i).join("/");
      status.set(dir, (status.get(dir) ?? true) && mine);
    }
  }
  return status;
}

function applyToGlobs(ctx, d) {
  const owned = new Set();
  const out = [];
  const dirs = fullyOwnedDirs(ctx, d.id);
  for (const p of d.patterns) {
    const matched = ctx.files.filter((f) => p.re.test(f) && !ctx.compiled.ignoreRes.some((re) => re.test(f)));
    const mine = matched.filter((f) => ctx.owners.get(f) === d.id && !owned.has(f));
    if (!mine.length) continue;
    if (mine.length === matched.length) {
      out.push(applyToSafe(p.glob));
      mine.forEach((f) => owned.add(f));
      continue;
    }
    for (const f of mine) {
      if (owned.has(f)) continue;
      const parts = f.split("/");
      // Highest fully-owned ancestor directory; fall back to the exact file.
      let top = null;
      for (let i = 1; i < parts.length; i++) {
        const dir = parts.slice(0, i).join("/");
        if (dirs.get(dir)) {
          top = dir;
          break;
        }
      }
      if (top) {
        out.push(applyToSafe(`${top}/**`));
        ctx.files.filter((x) => x.startsWith(`${top}/`)).forEach((x) => owned.add(x));
      } else {
        out.push(applyToSafe(f));
        owned.add(f);
      }
    }
  }
  return [...new Set(out)];
}

function renderInstructions(ctx, d) {
  return [
    "---",
    `applyTo: "${applyToGlobs(ctx, d).join(",")}"`,
    "---",
    "",
    INSTRUCTIONS_MARK,
    "",
    `These files belong to Mint's **${d.title}** domain (\`${d.id}\`). Before editing, read [the domain card](../../${CARDS_DIR}/${d.id}.md) for owned files, invariants, cross-domain contracts and focused validation. If the change spills into another domain, follow the large-task protocol in [AGENTS.md](../../AGENTS.md).`,
    "",
  ].join("\n");
}

/** Every file `sync` owns, mapped to its expected content. */
function expectedOutputs(ctx) {
  const out = new Map();
  for (const d of ctx.compiled.domains) {
    const cardPath = `${CARDS_DIR}/${d.id}.md`;
    const current = existsSync(abs(cardPath)) ? read(cardPath) : `${cardSkeleton(d)}\n${GEN_START}\n${GEN_END}\n`;
    const withBlock = splitCard(current).hasBlock ? current : `${current.trimEnd()}\n\n${GEN_START}\n${GEN_END}\n`;
    out.set(cardPath, replaceBlock(withBlock, renderCardBlock(ctx, d)));
    out.set(`${INSTRUCTIONS_DIR}/${d.id}.instructions.md`, renderInstructions(ctx, d));
  }
  out.set(`${CARDS_DIR}/README.md`, renderIndex(ctx));
  const agentsMd = read("AGENTS.md");
  if (agentsMd.includes(GEN_START)) out.set("AGENTS.md", replaceBlock(agentsMd, renderRoutingBlock(ctx)));
  return out;
}

function orphanInstructionFiles(ctx) {
  if (!existsSync(abs(INSTRUCTIONS_DIR))) return [];
  const ids = new Set(ctx.compiled.domains.map((d) => d.id));
  return readdirSync(abs(INSTRUCTIONS_DIR))
    .filter((n) => n.endsWith(".instructions.md") && !ids.has(n.replace(/\.instructions\.md$/, "")))
    .map((n) => `${INSTRUCTIONS_DIR}/${n}`)
    .filter((p) => read(p).includes(INSTRUCTIONS_MARK));
}

// ---------- commands ----------

function cmdSync() {
  // Two passes: new cards/instructions become owned files and can change the rendered lists.
  for (let pass = 0; pass < 2; pass++) {
    const ctx = loadContext();
    for (const [p, content] of expectedOutputs(ctx)) {
      if (existsSync(abs(p)) && read(p) === content) continue;
      mkdirSync(path.dirname(abs(p)), { recursive: true });
      writeFileSync(abs(p), content);
      if (pass === 0) console.log(`updated ${p}`);
    }
    for (const p of orphanInstructionFiles(ctx)) {
      rmSync(abs(p));
      console.log(`removed ${p}`);
    }
  }
  return cmdCheck({ quiet: true });
}

function markdownLinkErrors(ctx) {
  const errors = [];
  const docs = ctx.files.filter((f) => f.endsWith(".md") && (f === "AGENTS.md" || f.startsWith("agents/") || f.startsWith(INSTRUCTIONS_DIR)));
  for (const doc of docs) {
    for (const m of read(doc).matchAll(/\]\(([^)\s]+)\)/g)) {
      const target = m[1];
      if (/^(?:[a-z]+:|#)/i.test(target)) continue;
      const file = path.posix.normalize(path.posix.join(path.posix.dirname(doc), target.split("#")[0]));
      if (!existsSync(abs(file))) errors.push(`${doc}: broken link ${target}`);
    }
  }
  return errors;
}

function cmdCheck({ strict = false, quiet = false } = {}) {
  const ctx = loadContext();
  const errors = [];
  const warnings = [];
  const { budgets = {} } = ctx.manifest;

  for (const f of ctx.unowned) errors.push(`unowned file: ${f} (add a path to agents/domains.json)`);
  for (const a of ctx.ambiguous) errors.push(`ambiguous owner for ${a.file}: ${a.domains.join(", ")} (make one pattern more specific)`);
  for (const d of ctx.compiled.domains) {
    for (const p of d.patterns) if (!ctx.patternHits.has(`${d.id}\0${p.glob}`)) errors.push(`${d.id}: pattern matches no files: ${p.glob}`);
    for (const g of d.guides) if (!existsSync(abs(g))) errors.push(`${d.id}: guide not found: ${g}`);
    const card = `${CARDS_DIR}/${d.id}.md`;
    if (existsSync(abs(card))) {
      const { manual } = splitCard(read(card));
      const bytes = Buffer.byteLength(manual);
      if (budgets.cardBytes && bytes > budgets.cardBytes) errors.push(`${card}: hand-written section is ${bytes} bytes (budget ${budgets.cardBytes}); move detail to a topic guide`);
      if (/\bTODO\b/.test(manual)) warnings.push(`${card}: contains TODO placeholders`);
    }
    const size = domainSize(ctx, d.id);
    if (budgets.domainFiles && size.files > budgets.domainFiles) warnings.push(`${d.id}: ${size.files} files exceeds budget ${budgets.domainFiles}; consider splitting (agents/working-at-scale.md)`);
    if (budgets.domainLines && size.lines > budgets.domainLines) warnings.push(`${d.id}: ${size.lines} lines exceeds budget ${budgets.domainLines}; consider splitting (agents/working-at-scale.md)`);
  }
  for (const g of ctx.manifest.alwaysRead ?? []) if (!existsSync(abs(g))) errors.push(`alwaysRead guide not found: ${g}`);
  if (!read("AGENTS.md").includes(GEN_START)) errors.push("AGENTS.md: routing table markers missing");

  for (const [p, content] of expectedOutputs(ctx)) {
    if (!existsSync(abs(p)) || read(p) !== content) errors.push(`stale generated file: ${p} (run npm run agents:sync)`);
  }
  for (const p of orphanInstructionFiles(ctx)) errors.push(`orphan generated file: ${p} (run npm run agents:sync)`);
  const ids = new Set(ctx.compiled.domains.map((d) => d.id));
  for (const n of existsSync(abs(CARDS_DIR)) ? readdirSync(abs(CARDS_DIR)) : []) {
    if (n !== "README.md" && n.endsWith(".md") && !ids.has(n.slice(0, -3))) errors.push(`orphan card ${CARDS_DIR}/${n}: remove it or add the domain`);
  }
  errors.push(...markdownLinkErrors(ctx));

  if (strict) errors.push(...warnings.splice(0));
  for (const w of warnings) console.warn(`warning: ${w}`);
  for (const e of errors) console.error(`error: ${e}`);
  if (errors.length) {
    console.error(`\nagents:check failed with ${errors.length} error(s).`);
    process.exitCode = 1;
  } else if (!quiet || warnings.length) {
    console.log(`agents:check ok — ${ctx.compiled.domains.length} domains, ${ctx.owners.size} owned files${warnings.length ? `, ${warnings.length} warning(s)` : ""}.`);
  }
}

function cmdRoute(args, { json }) {
  if (!args.length) throw new Error('usage: npm run agents -- route "<task description>" [paths...]');
  const ctx = loadContext();
  const ranked = routeQuery(ctx.compiled, ctx.owners, args);
  const top = ranked[0]?.score ?? 0;
  const picked = ranked.filter((r) => r.score >= Math.max(3, top * 0.4)).slice(0, 4);
  const byId = new Map(ctx.compiled.domains.map((d) => [d.id, d]));
  const guides = [...new Set(picked.flatMap((r) => byId.get(r.id).guides))];
  const result = {
    domains: picked.map((r) => ({ ...r, card: `${CARDS_DIR}/${r.id}.md` })),
    read: [...(ctx.manifest.alwaysRead ?? []), ...picked.map((r) => `${CARDS_DIR}/${r.id}.md`), ...guides],
    multiDomain: picked.length > 1,
  };
  if (json) return console.log(JSON.stringify(result, null, 2));
  if (!picked.length) {
    console.log("No confident match. Read agents/domains/README.md and pick domains manually, or pass file paths.");
    return;
  }
  console.log("Domains (most relevant first):");
  for (const r of result.domains) console.log(`  ${r.id.padEnd(12)} score ${String(r.score).padStart(2)}  ${r.card}  — ${r.why.slice(0, 4).join("; ")}`);
  console.log("\nRead, in order:");
  for (const p of [...new Set(result.read)]) console.log(`  ${p}`);
  if (result.multiDomain) console.log("\nSpans several domains: follow the large-task protocol in AGENTS.md (contracts first, then one sub-task per domain).");
}

function changedFiles(base) {
  const set = new Set();
  const add = (lines) => lines.forEach((f) => set.add(f));
  if (base) add(gitLines("diff", "--name-only", `${base}...HEAD`));
  add(gitLines("diff", "--name-only", "HEAD"));
  add(gitLines("ls-files", "--others", "--exclude-standard"));
  return [...set].sort();
}

function cmdAffected(args, { json }) {
  const baseIdx = args.indexOf("--base");
  const base = baseIdx >= 0 ? args[baseIdx + 1] : null;
  const ctx = loadContext();
  const changed = changedFiles(base);
  const { owners, unowned, ambiguous } = resolveOwnership(ctx.compiled, changed);
  const domains = [...new Set(owners.values())].sort();
  const byId = new Map(ctx.compiled.domains.map((d) => [d.id, d]));
  const scopeFiles = [...new Set([...owners.keys(), ...domains.flatMap((id) => filesOf(ctx, id).filter((f) => TEST_FILE.test(f)))])].filter((f) => ctx.fileSet.has(f));
  const { cmds, notes } = validationFor(ctx, scopeFiles, domains.flatMap((id) => byId.get(id).validate), [...owners.keys()]);
  // New, deleted or renamed files and handbook edits can make generated maps stale.
  const tracked = new Set(gitLines("ls-files"));
  const reshaped = changed.some((f) => !existsSync(abs(f)) || !tracked.has(f) || f === MANIFEST || f.startsWith("agents/") || f === "AGENTS.md");
  if (reshaped && !cmds.includes("npm run agents:check")) cmds.unshift("npm run agents:check");
  const result = { base: base ?? "HEAD (working tree)", changed: changed.length, domains, unowned, ambiguous: ambiguous.map((a) => a.file), commands: cmds, notes };
  if (json) return console.log(JSON.stringify(result, null, 2));
  if (!changed.length) return console.log("No changes detected.");
  console.log(`Changed files: ${changed.length} (vs ${result.base})`);
  for (const id of domains) console.log(`  ${id.padEnd(12)} ${[...owners].filter(([, d]) => d === id).length} file(s)`);
  for (const f of [...unowned, ...result.ambiguous]) console.log(`  ⚠ no single owner: ${f} — update agents/domains.json, then npm run agents:sync`);
  console.log("\nFocused validation:");
  for (const c of cmds) console.log(`  ${c}`);
  for (const n of notes) console.log(`\nNote: ${n}`);
}

function cmdMap([id]) {
  const ctx = loadContext();
  const d = ctx.compiled.domains.find((x) => x.id === id);
  if (!d) throw new Error(`unknown domain "${id}". Known: ${ctx.compiled.domains.map((x) => x.id).join(", ")}`);
  const size = domainSize(ctx, id);
  const { budgets = {} } = ctx.manifest;
  console.log(`# ${d.title} (${id}) — ${size.files}/${budgets.domainFiles ?? "∞"} files, ${size.lines}/${budgets.domainLines ?? "∞"} lines\n`);
  for (const f of filesOf(ctx, id)) {
    const s = source(ctx, f);
    const n = s ? s.split("\n").length : 0;
    const ex = s && SOURCE_EXT.test(f) ? exportedNames(s) : [];
    console.log(`${f}${n ? ` (${n})` : ""}${ex.length ? ` — ${ex.join(", ")}` : ""}`);
  }
  const g = importGraph(ctx);
  const show = (title, entries) => {
    if (!entries.length) return;
    console.log(`\n## ${title}`);
    for (const [other, edges] of entries) {
      console.log(`- ${other} (${edges.length})`);
      for (const [a, b] of edges.slice(0, 12)) console.log(`    ${a} -> ${b}`);
      if (edges.length > 12) console.log(`    … ${edges.length - 12} more`);
    }
  };
  show("Imports from other domains", [...(g.get(id) ?? [])].sort());
  show("Imported by other domains", [...g].filter(([, m]) => m.has(id)).map(([o, m]) => [o, m.get(id)]).sort());
}

function cmdOwner(paths, { json }) {
  const ctx = loadContext();
  const res = resolveOwnership(ctx.compiled, paths.map((p) => p.replace(/^\.\//, "")));
  const out = Object.fromEntries([...res.owners, ...res.unowned.map((f) => [f, null]), ...res.ambiguous.map((a) => [a.file, a.domains])]);
  if (json) return console.log(JSON.stringify(out, null, 2));
  for (const [f, d] of Object.entries(out)) console.log(`${f}: ${d === null ? "UNOWNED" : Array.isArray(d) ? `AMBIGUOUS (${d.join(", ")})` : d}`);
}

const HELP = `Mint agent domain tooling

  npm run agents -- route "<task>" [paths…]   Which domains/cards to read for a task
  npm run agents -- affected [--base <ref>]   Domains touched by local changes + focused validation
  npm run agents -- map <domain>              Live file/export/import map for one domain
  npm run agents -- owner <path…>             Owning domain for files
  npm run agents:sync                         Regenerate cards, index, routing table, path instructions
  npm run agents:check [-- --strict]          Validate ownership, freshness, budgets and links (CI)

Add --json to route/affected/owner for machine-readable output.`;

const [command, ...rest] = process.argv.slice(2);
const json = rest.includes("--json");
const args = rest.filter((a) => a !== "--json" && a !== "--strict");
try {
  switch (command) {
    case "sync":
      cmdSync();
      break;
    case "check":
      cmdCheck({ strict: rest.includes("--strict") });
      break;
    case "route":
      cmdRoute(args, { json });
      break;
    case "affected":
      cmdAffected(args, { json });
      break;
    case "map":
      cmdMap(args);
      break;
    case "owner":
      cmdOwner(args, { json });
      break;
    default:
      console.log(HELP);
      if (command && command !== "help") process.exitCode = 1;
  }
} catch (error) {
  console.error(`agents: ${error.message}`);
  process.exitCode = 1;
}
