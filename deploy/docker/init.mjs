// First-boot setup for the compose stack. Runs as root in the `init` service, then exits.
//  - generates the secrets Mint needs (kept in the `secrets` volume, stable across restarts)
//  - creates the music and blackhole folders and hands them to PUID:PGID
//  - prints the admin login
// `node init.mjs vercel` prints the variables a Vercel-hosted website must share with this server.
import { randomBytes } from "node:crypto";
import { chownSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";

const dir = process.env.MINT_SECRETS_DIR ?? "/secrets";
const file = `${dir}/mint.env`;
const uid = Number(process.env.PUID ?? 1000);
const gid = Number(process.env.PGID ?? 1000);

const read = (f) => (existsSync(f) ? readFileSync(f, "utf8").trim() : "");
const saved = existsSync(file)
  ? Object.fromEntries(
      readFileSync(file, "utf8")
        .split("\n")
        .filter((l) => l.includes("=") && !l.startsWith("#"))
        .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
    )
  : {};
if (read(`${dir}/admin_password`)) saved.ADMIN_PASSWORD = read(`${dir}/admin_password`);

const generators = {
  ENCRYPTION_KEY: () => randomBytes(32).toString("base64"),
  MINT_SIGNING_SECRET: () => randomBytes(48).toString("base64url"),
  POSTGRES_PASSWORD: () => randomBytes(24).toString("hex"),
  ADMIN_PASSWORD: () => randomBytes(12).toString("base64url"),
};

// The first value ever used wins, so changing .env later can't strand the database or encrypted tokens.
const values = { ...saved };
const created = [];
for (const [key, gen] of Object.entries(generators)) {
  if (values[key]) continue;
  values[key] = process.env[key] || gen();
  if (!process.env[key]) created.push(key);
}

if (process.argv[2] === "vercel") {
  console.log("# Paste into Vercel -> Settings -> Environment Variables");
  for (const k of ["ENCRYPTION_KEY", "MINT_SIGNING_SECRET"]) console.log(`${k}=${values[k]}`);
  process.exit(0);
}

mkdirSync(dir, { recursive: true });
// The admin password goes in its own file read only by the worker's first-run seed, not into every container's env.
const { ADMIN_PASSWORD: adminPassword, ...shared } = values;
const body = Object.entries(shared).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
writeFileSync(file, `# Generated by mint init on first boot. Keep this volume; deleting it orphans the database.\n${body}`, { mode: 0o600 });
// Postgres reads its password from its own file and runs as a different uid.
writeFileSync(`${dir}/postgres_password`, values.POSTGRES_PASSWORD, { mode: 0o644 });
writeFileSync(`${dir}/admin_password`, adminPassword, { mode: 0o600 });
chownSync(dir, uid, gid);
for (const f of [file, `${dir}/admin_password`]) chownSync(f, uid, gid);

for (const p of ["/music", "/blackhole", "/blackhole/torrents", "/blackhole/nzbs", "/blackhole/downloads", "/blackhole/usenet-downloads", "/data/staging"]) {
  if (!existsSync(p.split("/").slice(0, 2).join("/"))) continue;
  mkdirSync(p, { recursive: true });
  const st = statSync(p);
  if (st.uid !== uid || st.gid !== gid) chownSync(p, uid, gid);
}

const email = process.env.ADMIN_EMAIL || "admin@mint.local";
const url = process.env.PUBLIC_URL || `https://${process.env.MINT_DOMAIN || "mint.example.com"}`;
console.log(created.length ? `mint init: generated ${created.join(", ")}` : "mint init: secrets already in place");
console.log(`\n  Mint is starting at ${url}`);
console.log(`  Admin login: ${email}`);
console.log(
  process.env.ADMIN_PASSWORD === adminPassword
    ? "  Password:    the ADMIN_PASSWORD you configured\n"
    : `  Password:    ${values.ADMIN_PASSWORD}\n  Keep this login private. Show it again by running the init container.\n`,
);
